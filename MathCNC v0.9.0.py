def _apply_implicit_multiplication(s):
    """
    Вставляет знаки умножения туда, где пользователь их не написал.

    Люди ленятся и пишут "2t" вместо "2*t" или "3sin(t)" вместо "3*sin(t)".
    Мы хотим это понимать. Но есть сложность: "sin" - это имя функции,
    и нельзя превращать его в "s*i*n". Поэтому сначала мы временно заменяем
    все известные имена функций на специальные невидимые символы, потом
    аккуратно расставляем "*", а в конце возвращаем имена обратно.

    Возвращает новую строку с расставленными умножениями.
    """
    # --- шаг 1: прячем имена функций в специальные символы ---
    # Список "заменителей" — пары (специальный символ, настоящее имя).
    placeholders = []

    # Сортируем имена по длине (сначала длинные), чтобы "asin" не был
    # пойман раньше, чем "sin". Иначе "asin(t)" превратился бы в "a*sin(t)".
    for i, fname in enumerate(sorted(FUNCTION_NAMES, key=len, reverse=True)):
        # Ищем "sin(" или "sin (" — имя функции, за которым идёт скобка.
        pattern = re.compile(rf'\b{fname}\s*\(')
        if pattern.search(s):
            # Символ из "личного" диапазона Unicode — таких символов в
            # обычной формуле не бывает, поэтому не перепутаем.
            token = chr(0xE000 + i)
            placeholders.append((token, fname))
            s = pattern.sub(f'{token}(', s)

    # Диапазон, в котором лежат наши "спрятанные" символы.
    # Нужен для регулярных выражений ниже.
    PU = "\uE000-\uE1FF"

    # --- шаг 2: расставляем умножения ---
    # Пи + буква или скобка: "pi x" -> "pi*x", "pi(" -> "pi*("
    s = re.sub(r'pi(?=[a-zA-Z(])', 'pi*', s)
    # Цифра + буква или скобка: "2t" -> "2*t", "2sin(...)" -> "2*sin(...)"
    s = re.sub(rf'(\d)([a-zA-Z({PU}])', r'\1*\2', s)
    # Закрывающая скобка + буква или скобка: ")t" -> ")*t", ")(" -> ")*("
    s = re.sub(rf'(\))([a-zA-Z({PU}])', r'\1*\2', s)
    # Буква + открывающая скобка: но это уже касается функций,
    # поэтому действует только на "не спрятанные" имена.
    s = re.sub(r'([a-zA-Z])(\()', r'\1*\2', s)
    # Буква + спрятанное имя функции: "x sin(t)" -> "x*<токен>(t)"
    s = re.sub(rf'([a-zA-Z])([{PU}])', r'\1*\2', s)

    # --- шаг 3: возвращаем имена функций на место ---
    for token, fname in placeholders:
        s = s.replace(token, fname)
    return s


def preprocess_formula(expr):
    """
    Приводит формулу к "нормальному" виду, понятному Python.

    Пользователь может написать по-разному: "2²", "2^2", "√x", "|x|",
    "ln(x)", "tg(x)". Все эти варианты нужно перевести в одно и то же:
    "2**2", "sqrt(x)", "abs(x)", "log(x)", "tan(x)".

    Принимает строку с формулой. Возвращает строку, готовую к разбору.
    """
    s = expr.strip()

    # --- заменяем красивые символы на обычные ---
    s = s.replace("π", "pi")                         # число пи
    s = s.replace("×", "*").replace("÷", "/")       # умножение и деление
    s = s.replace("·", "*").replace("⋅", "*")       # ещё умножение
    s = s.replace("−", "-").replace("–", "-").replace("—", "-")  # дефисы
    # Верхние индексы: "x²" -> "x**2"
    s = s.replace("²", "**2").replace("³", "**3")
    s = s.replace("⁴", "**4").replace("⁵", "**5")
    s = s.replace("⁶", "**6").replace("⁷", "**7")
    s = s.replace("⁸", "**8").replace("⁹", "**9")

    # --- квадратный корень ---
    # "√x" или "√2" -> "sqrt(x)" или "sqrt(2)"
    s = re.sub(r'√\s*([a-zA-Z]|\d+\.?\d*)', r'sqrt(\1)', s)
    s = s.replace("√", "sqrt")    # оставшиеся просто меняем на "sqrt"

    # --- модуль в виде |x| ---
    # Пять раз подряд, чтобы обработать вложенные |x| + |y| и подобное.
    for _ in range(5):
        new = re.sub(r'\|([^|]*)\|', r'abs(\1)', s)
        if new == s:
            break
        s = new

    # --- возведение в степень через "^" ---
    # В Python "^" — это побитовое исключающее ИЛИ, а не степень.
    # Поэтому заменяем на "**".
    s = s.replace("^", "**")

    # --- русские и привычные обозначения ---
    s = re.sub(r'\bln\s*\(', 'log(', s)          # натуральный логарифм
    s = re.sub(r'\blg\s*\(', 'log10(', s)        # десятичный
    s = re.sub(r'\barcsin\s*\(', 'asin(', s)     # обратный синус
    s = re.sub(r'\barccos\s*\(', 'acos(', s)     # обратный косинус
    s = re.sub(r'\barctg\s*\(', 'atan(', s)      # арктангенс (по-русски)
    s = re.sub(r'\barctan\s*\(', 'atan(', s)     # и по-английски
    s = re.sub(r'\btg\s*\(', 'tan(', s)          # тангенс по-русски
    s = re.sub(r'\bctg\s*\(', 'cot(', s)         # котангенс по-русски

    # В самом конце — расставляем недостающие умножения.
    return _apply_implicit_multiplication(s)


def compile_formula(expr):
    """
    Превращает текст формулы в настоящую функцию.

    Например, из "2*t + sin(t)" делает функцию f, такую что
    f(0) = 0, f(pi/2) = pi + 1 и т.д.

    Принимает строку с формулой. Возвращает функцию одного аргумента t.

    Безопасность: разрешены только цифры, буквы, знаки действий и скобки.
    Никаких "import", "open", "exec" и прочих опасных слов не пройдёт.
    """
    expr = preprocess_formula(expr)

    # --- проверка на посторонние символы ---
    # Ищем всё, что НЕ входит в разрешённый набор.
    if re.search(r"[^0-9a-zA-Z_+\-*/().,\s]", expr):
        bad = sorted(set(re.findall(r"[^0-9a-zA-Z_+\-*/().,\s]", expr)))
        raise ValueError("Недопустимые символы: " + " ".join(bad))

    # --- защита от двойного подчёркивания ---
    # В Python имена с "__" часто означают что-то системное. Запрещаем.
    if "__" in expr:
        raise ValueError("Двойное подчёркивание запрещено.")

    # --- превращаем текст в выполняемый код ---
    try:
        code = compile(expr, "<формула>", "eval")
    except SyntaxError as e:
        raise ValueError(f"Синтаксическая ошибка: {e.msg}")

    # Возвращаемая функция. При каждом вызове eval выполняет
    # заранее собранный код, подставляя t и все разрешённые функции.
    # "__builtins__": {} означает "не давать доступ к встроенным функциям".
    def f(t):
        return eval(code, {"__builtins__": {}}, {**SAFE_FUNCTIONS, "t": t})

    return f


# ===РАБОТА С КРИВЫМИ===
# ----------------------------------------------------------------------------
# Кривая - это список точек (x, y). Одна функция может вернуть несколько
# отдельных кусков (например, гипербола разрывается на две ветви, тангенс -
# на много кусков). Здесь мы приводим всё к единому виду и готовим к отрисовке.

def normalize_curves(data):
    """
    Приводит список кривых к единому формату.

    Иногда удобно передать одну кривую просто как список точек.
    Иногда — как список из нескольких кривых. Эта функция понимает оба варианта
    и всегда возвращает список из кривых, где каждая кривая — список точек.
    """
    if not data:
        return []

    # Если первый элемент - точка (пара чисел), значит это одна кривая.
    first = data[0]
    if (isinstance(first, (tuple, list)) and len(first) == 2
            and all(isinstance(v, (int, float)) for v in first)):
        return [list(data)]

    # Иначе - это уже список кривых, но некоторые могут быть пустыми.
    # Пустые выкидываем.
    return [list(c) for c in data if c]


def check_curves(curves):
    """
    Проверяет, что данные пригодны для отрисовки.

    Иначе станок может получить странные числа (NaN, бесконечность)
    и сойти с ума. Поэтому перед работой аккуратно всё перепроверяем.
    Если что-то не так — выбрасываем понятную ошибку.
    """
    if not curves:
        raise ValueError("Нет данных для построения.")
    for i, c in enumerate(curves):
        if not c:
            raise ValueError(f"Кривая {i + 1} пустая.")
        for x, y in c:
            if not (isinstance(x, (int, float))
                    and isinstance(y, (int, float))):
                raise ValueError(f"Плохая точка в кривой {i + 1}: ({x}, {y})")
            try:
                # math.isfinite(x) - это проверка "обычное ли число".
                # NaN и бесконечность - не обычные, их нельзя рисовать.
                if not (math.isfinite(x) and math.isfinite(y)):
                    raise ValueError(
                        f"NaN/Inf в кривой {i + 1}: ({x}, {y})")
            except OverflowError:
                raise ValueError(f"Слишком большое число в кривой {i + 1}")


def extract_singularities(expr, t0, t1, n):
    """
    Ищет точки разрыва (выколотые точки) в формуле.
    
    Анализирует выражение, находит знаменатели (всё, что стоит после знака "/")
    и ищет их корни на отрезке [t0, t1]. В этих точках функция уходит
    в бесконечность или имеет выколотую точку (как в (t²-4)/(t-2) при t=2).
    
    Возвращает список значений t, где кривая должна прерваться.
    """
    try:
        expr = preprocess_formula(expr)
        tree = ast.parse(expr, mode='eval')
    except Exception:
        return []
    
    denominators = []
    for node in ast.walk(tree):
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Div):
            denominators.append(node.right)
            
    if not denominators:
        return []
        
    singularities = []
    grid = [t0 + (t1 - t0) * i / max(n // 10, 100) 
            for i in range(max(n // 10, 100) + 1)]
    
    for den in denominators:
        try:
            code = compile(ast.Expression(den), "<den>", "eval")
            def f(t):
                return eval(code, {"__builtins__": {}}, {**SAFE_FUNCTIONS, "t": t})
        except Exception:
            continue
            
        prev_val = None
        prev_t = None
        for t in grid:
            try:
                val = f(t)
                if not isinstance(val, (int, float)):
                    continue
                if not math.isfinite(val):
                    singularities.append(t)
                    continue
                if abs(val) < 1e-12:
                    singularities.append(t)
                    continue
                if prev_val is not None:
                    if (prev_val > 0 and val < 0) or (prev_val < 0 and val > 0):
                        # Есть корень между prev_t и t. Ищем бисекцией.
                        a, b = prev_t, t
                        fa = prev_val
                        for _ in range(40):
                            mid = (a + b) / 2
                            try:
                                fm = f(mid)
                                if not isinstance(fm, (int, float)):
                                    break
                                if not math.isfinite(fm):
                                    break
                                if (fa > 0 and fm < 0) or (fa < 0 and fm > 0):
                                    b = mid
                                else:
                                    a = mid
                                    fa = fm
                            except Exception:
                                break
                        singularities.append((a + b) / 2)
                prev_val = val
                prev_t = t
            except Exception:
                pass
                
    unique_singularities = []
    for s in sorted(singularities):
        if not unique_singularities or abs(s - unique_singularities[-1]) > 1e-6:
            unique_singularities.append(s)
    return unique_singularities


def get_singularity_points(fx, fy, t0, t1, n):
    """
    Возвращает список точек (x, y), в которых параметрическая кривая
    имеет разрыв (выколотую точку).

    Проходит по сетке параметров, ищет места, где функция вылетает
    (NaN/Inf), и запоминает последнюю нормальную точку перед вылетом.
    Так мы получаем координаты, вокруг которых надо нарисовать кружок.
    """
    pts = []
    if n < 2:
        return pts
    prev_x = prev_y = None
    # Густая сетка, чтобы поймать момент скачка.
    steps = max(200, min(n, 4000))
    for i in range(steps + 1):
        t = t0 + (t1 - t0) * i / steps
        try:
            x, y = fx(t), fy(t)
            if not (math.isfinite(x) and math.isfinite(y)):
                raise ValueError
        except Exception:
            # Точка вылетела — фиксируем предыдущую как "границу".
            if prev_x is not None:
                pts.append((prev_x, prev_y))
            prev_x = prev_y = None
            continue
        if prev_x is not None:
            # Резкий скачок между соседними точками — тоже разрыв.
            d = math.hypot(x - prev_x, y - prev_y)
            if d > 1e6:
                pts.append((prev_x, prev_y))
        prev_x, prev_y = x, y
    return pts


def make_points(fx, fy, t0, t1, n, singularities=None):
    """
    Строит точки параметрической кривой.

    У нас есть две функции: fx(t) — даёт x, fy(t) — даёт y.
    Мы пробегаем параметр t от t0 до t1 с шагом (t1-t0)/n,
    в каждой точке считаем (x, y) и собираем результат.

    Возвращает список кусков. Один кусок — это непрерывный набор точек.
    Кусков может быть несколько, если кривая где-то рвётся (например,
    тангенс уходит в бесконечность или гипербола перескакивает через ноль).

    Дополнительно делаем две вещи:
      1) отрезаем "выбросы" — точки, которые дико далеко от остальных.
         Обычно это артефакт из-за деления на очень маленькое число.
      2) рвём кривую в местах, где расстояние между соседними точками
         слишком большое — это явный разрыв, а не плавная линия.
    """
    # Ограничиваем количество точек разумными рамками.
    try:
        n = int(n)
    except Exception:
        n = 3000
    n = max(2, min(n, MAX_N))

    if t1 <= t0:
        return []

    # --- шаг 1: считаем точки ---
    raw_pts = []
    
    if singularities is None:
        singularities = []
    
    # Шаг по t
    dt = (t1 - t0) / n
    # Размер "выколотой" точки (пропускаем кусочек кривой вокруг разрыва)
    gap_t = max(dt * 2, (t1 - t0) / 300)

    for i in range(n + 1):
        t = t0 + (t1 - t0) * i / n
        
        # Проверяем, не попали ли мы в выколотую точку
        is_hole = False
        for s in singularities:
            if abs(t - s) < gap_t:
                is_hole = True
                break
        if is_hole:
            raw_pts.append(None)
            continue
            
        try:
            x, y = fx(t), fy(t)
            if math.isfinite(x) and math.isfinite(y):
                raw_pts.append((x, y))
            else:
                # Бесконечность или NaN - помечаем как "дырку".
                raw_pts.append(None)
        except Exception:
            # Ошибка вычисления (деление на ноль и т.п.) - тоже "дырка".
            raw_pts.append(None)

    # --- шаг 2: ищем "выбросы" ---
    # Берём медианные (типичные) значения координат и сравниваем с ними.
    # Если какая-то точка в 20 раз дальше медианы — считаем её выбросом.
    finite_pts = [p for p in raw_pts if p is not None]
    if len(finite_pts) >= 20:
        abs_x = sorted(abs(p[0]) for p in finite_pts)
        abs_y = sorted(abs(p[1]) for p in finite_pts)
        med_x = abs_x[len(abs_x) // 2] or 1e-9
        med_y = abs_y[len(abs_y) // 2] or 1e-9
        factor = 20.0
        limit_x = med_x * factor if abs_x[-1] / med_x > factor else abs_x[-1]
        limit_y = med_y * factor if abs_y[-1] / med_y > factor else abs_y[-1]
    else:
        # Слишком мало точек — не будем ничего отрезать.
        limit_x = limit_y = float("inf")

    # --- шаг 3: режем на куски ---
    pieces = []
    current = []
    for p in raw_pts:
        if p is None:
            # Дырка - завершаем текущий кусок.
            if current:
                pieces.append(current)
                current = []
            continue
        if abs(p[0]) > limit_x or abs(p[1]) > limit_y:
            # Выброс - тоже завершаем кусок.
            if current:
                pieces.append(current)
                current = []
            continue
        current.append(p)
    if current:
        pieces.append(current)

    # --- шаг 4: разрываем в местах, где точки слишком далеко друг от друга ---
    # Порог: 30% от общего размаха. Если между соседними точками больше —
    # это разрыв, а не плавная линия.
    all_pts = [p for piece in pieces for p in piece]
    if len(all_pts) >= 2:
        xs = [p[0] for p in all_pts]
        ys = [p[1] for p in all_pts]
        span = max(max(xs) - min(xs), max(ys) - min(ys), 1e-9)
        threshold = 0.30 * span
    else:
        threshold = float("inf")

    final_pieces = []
    for piece in pieces:
        if not piece:
            continue
        current = [piece[0]]
        for i in range(1, len(piece)):
            p = piece[i]
            prev = current[-1]
            d = math.hypot(p[0] - prev[0], p[1] - prev[1])
            if d > threshold:
                # Слишком далеко — начинаем новый кусок.
                if len(current) >= 2:
                    final_pieces.append(current)
                current = [p]
            else:
                current.append(p)
        if len(current) >= 2:
            final_pieces.append(current)

    return final_pieces


def math_bbox(curves):
    """
    Возвращает "рамку" вокруг всех точек: (x_min, x_max, y_min, y_max).

    Проще говоря: находит левый, правый, нижний и верхний края рисунка.
    Нужно, чтобы потом подогнать масштаб под рабочее поле.
    """
    curves = normalize_curves(curves)
    xs = [p[0] for c in curves for p in c]
    ys = [p[1] for c in curves for p in c]
    return min(xs), max(xs), min(ys), max(ys)


def linspace(a, b, n):
    """
    Возвращает список из (n+1) равномерно распределённых чисел от a до b.

    Просто удобная функция, чтобы не писать цикл каждый раз.
    Пример: linspace(0, 1, 4) = [0.0, 0.25, 0.5, 0.75, 1.0]
    """
    return [a + (b - a) * i / n for i in range(n + 1)]



