def build_for_spec(spec, params):
    """
    Собирает кривые по описанию и параметрам.

    Возвращает пару (список кривых, подпись).
    Работает и для базовых функций (у которых есть "build"),
    и для параметрических (у которых есть "fx" и "fy").
    """
    # Базовые функции — вызываем готовую функцию сборки.
    if "build" in spec:
        _build_drawing_inner._last_holes = None
        curves = spec["build"](params)
        label = spec["label"](params)
        return normalize_curves(curves), label

    # Параметрические — берём формулы (из пресета или из ввода пользователя).
    if "fx" in spec:
        fx_expr, fy_expr = spec["fx"], spec["fy"]
    else:
        fx_expr, fy_expr = params["fx"], params["fy"]

    # Компилируем обе формулы в функции Python.
    fx = compile_formula(fx_expr)
    fy = compile_formula(fy_expr)

    # Достаём t0, t1, n с проверкой.
    try:
        n_val = int(float(params.get("n", 3000)))
    except Exception:
        n_val = 3000
    n_val = max(2, min(n_val, MAX_N))

    try:
        t0 = float(params.get("t0", -5.0))
    except Exception:
        t0 = -5.0
    try:
        t1 = float(params.get("t1", 5.0))
    except Exception:
        t1 = 5.0

    # Ищем выколотые точки (разрывы) в формулах
    sing_x = extract_singularities(fx_expr, t0, t1, n_val)
    sing_y = extract_singularities(fy_expr, t0, t1, n_val)
    singularities = sing_x + sing_y

    curves = make_points(fx, fy, t0, t1, n_val, singularities)

    # --- НОВОЕ: запоминаем координаты выколотых точек ---
    holes = []
    for s in singularities:
        try:
            hx, hy = fx(s), fy(s)
            if math.isfinite(hx) and math.isfinite(hy):
                holes.append((hx, hy))
        except Exception:
            pass
    _build_drawing_inner._last_holes = holes
    # -----------------------------------------------------

    label = custom_label(fx_expr, fy_expr)
    return curves, label



