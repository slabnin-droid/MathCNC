# Готовые "заготовки" для стандартных графиков. Каждая функция получает
# параметры и возвращает список точек (x, y).


def plot_linear(k, b, x0, x1, n=1000):
    """Прямая: y = k*x + b на промежутке [x0, x1]."""
    return [(x, k * x + b) for x in linspace(x0, x1, n)]


def plot_quadratic(a, b, c, x0, x1, n=2000):
    """Парабола: y = a*x² + b*x + c."""
    return [(x, a * x * x + b * x + c) for x in linspace(x0, x1, n)]


def plot_cubic(a, b, c, d, x0, x1, n=3000):
    """Кубическая: y = a*x³ + b*x² + c*x + d."""
    return [(x, a * x ** 3 + b * x * x + c * x + d)
            for x in linspace(x0, x1, n)]


def plot_hyperbola(k, x0, x1, n=2000):
    """
    Гипербола: y = k/x.

    Из-за деления на x около нуля получаем разрыв. Поэтому строим
    отдельно левую и правую ветви. Плюс-минус "эпсилон" — чтобы не
    делить на ноль.
    """
    radius = max(abs(x0), abs(x1), 0.01)
    eps = max(radius / 100, 1e-3)
    n2 = max(n // 2, 100)
    curves = []
    if x1 > eps:
        right_lo = max(x0, eps)
        if x1 > right_lo:
            curves.append([(x, k / x)
                           for x in linspace(right_lo, x1, n2)])
    if x0 < -eps:
        left_hi = min(x1, -eps)
        if left_hi > x0:
            curves.append([(x, k / x)
                           for x in linspace(x0, left_hi, n2)])
    return curves


def plot_sqrt(a, x0, x1, n=2000):
    """
    Корень: y = a*√x. Область определения — x >= 0.
    Если x1 <= 0 — возвращаем пустой список (нечего рисовать).
    """
    x0 = max(x0, 0.0)
    if x1 <= x0:
        return []
    return [(x, a * math.sqrt(x)) for x in linspace(x0, x1, n)]


def plot_sin(A, omega, phi, periods, n=3000):
    """
    Синус: y = A * sin(omega*x + phi).
    Строит указанное количество периодов.
    """
    periods = max(0.001, min(periods, MAX_PERIODS))
    if abs(omega) < 1e-9:
        # omega = 0 — синус превращается в постоянную A*sin(phi).
        return [(x, A * math.sin(phi))
                for x in linspace(0, 2 * math.pi, n)]
    t1 = 2 * math.pi * periods / abs(omega)
    return [(x, A * math.sin(omega * x + phi))
            for x in linspace(0, t1, n)]


def plot_cos(A, omega, phi, periods, n=3000):
    """Косинус: y = A * cos(omega*x + phi)."""
    periods = max(0.001, min(periods, MAX_PERIODS))
    if abs(omega) < 1e-9:
        return [(x, A * math.cos(phi))
                for x in linspace(0, 2 * math.pi, n)]
    t1 = 2 * math.pi * periods / abs(omega)
    return [(x, A * math.cos(omega * x + phi))
            for x in linspace(0, t1, n)]


def plot_tan(A, omega, periods, n=4000):
    """
    Тангенс: y = A * tan(omega*x).

    У тангенса есть вертикальные асимптоты (уходит в бесконечность).
    Чтобы не рисовать линии до бесконечности, ограничиваем y сверху-снизу
    и рвём кривую в местах, где она "вылетает" за предел.
    """
    if abs(omega) < 1e-9:
        raise ValueError("ω не может быть 0 для tan.")
    periods = max(0.001, min(periods, MAX_PERIODS))
    T = math.pi / abs(omega)
    # Начинаем с середины между асимптотами, чтобы не начинать с разрыва.
    t0, t1 = -T / 2, periods * T - T / 2
    y_limit = min(max(abs(A) * 5, 5), 30)     # ограничение по y
    curves, current = [], []
    for x in linspace(t0, t1, n):
        try:
            y = A * math.tan(omega * x)
            if abs(y) > y_limit:
                # Слишком большое — режем кривую.
                if current:
                    curves.append(current)
                    current = []
                continue
            current.append((x, y))
        except (ValueError, ZeroDivisionError):
            if current:
                curves.append(current)
                current = []
    if current:
        curves.append(current)
    return curves


def plot_abs(a, b, x0, x1, n=1500):
    """Модуль: y = a*|x| + b."""
    return [(x, a * abs(x) + b) for x in linspace(x0, x1, n)]



