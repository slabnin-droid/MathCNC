def ask_float(prompt, default):
    """Спрашивает число у пользователя (или возвращает значение по умолчанию)."""
    s = input(f"{prompt} [{default}]: ").strip()
    if not s:
        return float(default)
    try:
        return float(s)
    except ValueError:
        print("   Введите число. Беру значение по умолчанию.")
        return float(default)


def ask_int(prompt, default):
    """Спрашивает целое число."""
    s = input(f"{prompt} [{default}]: ").strip()
    if not s:
        return int(default)
    try:
        return int(s)
    except ValueError:
        print("   Введите целое. Беру значение по умолчанию.")
        return int(default)


def ask_str(prompt, default):
    """Спрашивает строку (пустой ввод = значение по умолчанию)."""
    s = input(f"{prompt} [{default}]: ").strip()
    return s or default


def ask_choice(prompt, options, default):
    """Спрашивает выбор из списка вариантов."""
    opts = " / ".join(options)
    while True:
        s = input(f"{prompt} ({opts}) [{default}]: ").strip()
        if not s:
            return default
        if s in options:
            return s
        print(f"   Введите одно из: {opts}")


def read_params_cli(spec):
    """Спрашивает все параметры функции из описанного списка."""
    out = {}
    for name, prompt, kind, default in spec["params"]:
        if kind == "float":
            out[name] = ask_float(prompt, default)
        elif kind == "int":
            out[name] = ask_int(prompt, default)
        else:
            out[name] = ask_str(prompt, default)
    return out


def show_cli_menu():
    """Печатает меню с доступными кривыми и возвращает списки ключей."""
    print("\n=== MathCNC ===")
    print("\nБазовые функции:")
    keys_b = list(BASE_FUNCTIONS.keys())
    for i, k in enumerate(keys_b, 1):
        print(f"  {i:>2}. {BASE_FUNCTIONS[k]['title']}")
    print("\nПараметрические кривые:")
    keys_p = list(PRESETS.keys())
    off = len(keys_b)
    for i, k in enumerate(keys_p, 1):
        print(f"  {off + i:>2}. {PRESETS[k]['title']}")
    print(f"  {off + len(keys_p) + 1:>2}. {CUSTOM_SPEC['title']}")
    return keys_b, keys_p


def run_cli():
    """Основной цикл текстового режима."""
    while True:
        keys_b, keys_p = show_cli_menu()
        total = len(keys_b) + len(keys_p) + 1
        raw = input("\nВыбор (q -- выход): ").strip().lower()
        if raw in ("q", "0", "exit", "quit"):
            break
        try:
            idx = int(raw)
        except ValueError:
            print("Неверный выбор.")
            continue
        if not 1 <= idx <= total:
            print("Неверный выбор.")
            continue

        # Определяем, что выбрал пользователь: базовую функцию,
        # параметрический пресет или свою формулу.
        if idx <= len(keys_b):
            key = keys_b[idx - 1]
            spec = BASE_FUNCTIONS[key]
            print(f"\n>>> {spec['title']}")
            params = read_params_cli(spec)
        elif idx <= len(keys_b) + len(keys_p):
            key = keys_p[idx - len(keys_b) - 1]
            spec = PRESETS[key]
            print(f"\n>>> {spec['title']}")
            print(f"    x(t) = {spec['fx']}")
            print(f"    y(t) = {spec['fy']}")
            params = read_params_cli(spec)
        else:
            key = "custom"
            spec = CUSTOM_SPEC
            print(f"\n>>> {spec['title']}")
            print("    Доступны: sin cos tan cot sec csc, asin acos atan,")
            print("              sinh cosh tanh, sqrt cbrt abs exp,")
            print("              log ln log10 lg log2, floor ceil round sign,")
            print("              atan2 pow min max, radians degrees")
            print("    Константы: pi π, e, tau")
            print("    Пример:    cos(t)  sin(t)+cos(2t)  |t|*sin(t)")
            params = read_params_cli(spec)

        # Собираем кривую.
        try:
            curves, label = build_for_spec(spec, params)
        except Exception as e:
            print(f"   Ошибка: {e}")
            continue

        all_pts = [p for c in curves for p in c]
        if not all_pts:
            print("   Нет точек.")
            continue

        # Параметры поля и оформления.
        field_w = ask_float("Ширина поля, мм", FIELD_W_DEFAULT)
        field_h = ask_float("Высота поля, мм", FIELD_H_DEFAULT)
        unit = ask_float("Единичный отрезок, мм (0 = авто)", UNIT_MM_DEFAULT)
        offset_x = ask_float("Доп. сдвиг X, мм", 0.0)
        offset_y = ask_float("Доп. сдвиг Y, мм", 0.0)
        align_x_ru = ask_choice("Прижать по горизонтали",
                                ["Слева", "По центру", "Справа"],
                                "По центру")
        align_y_ru = ask_choice("Прижать по вертикали",
                                ["Снизу", "По центру", "Сверху"],
                                "По центру")
        align_x = {"Слева": "left", "По центру": "center",
                   "Справа": "right"}[align_x_ru]
        align_y = {"Снизу": "bottom", "По центру": "center",
                   "Сверху": "top"}[align_y_ru]
        draw_axes = ask_choice("Рисовать оси", ["да", "нет"], "да") == "да"
        show_label = ask_choice("Подпись функции", ["да", "нет"], "да") == "да"
        feed = ask_int("Скорость, мм/мин", FEED_DEFAULT)

        # Автомасштаб (если попросили 0).
        xmin, xmax = math_bbox(curves)[:2]
        ymin, ymax = math_bbox(curves)[2:]
        w_math, h_math = xmax - xmin, ymax - ymin
        if unit <= 0:
            unit = fit_unit_to_field(w_math, h_math, field_w, field_h,
                                     label_text=label if show_label else "")
            print(f"   Авто-масштаб: unit = {unit:.3f}")

        # Собираем чертёж.
        try:
            decorated_mm, info = build_drawing(
                curves, unit, draw_axes, label if show_label else "",
                offset_x_mm=offset_x, offset_y_mm=offset_y,
                align_x=align_x, align_y=align_y,
                field_w=field_w, field_h=field_h)
        except Exception as e:
            print(f"   Ошибка при сборке: {e}")
            continue

        used_unit = info["unit_mm"]
        if used_unit < unit - 1e-6:
            print(f"   ⚠ Автосжатие: unit {unit:.3f} → {used_unit:.3f}")

        # Спрашиваем имя файла и сохраняем.
        fname = input(f"\nИмя файла [{key}.gcode]: ").strip() \
            or f"{key}.gcode"
        if not fname.endswith(".gcode"):
            fname += ".gcode"

        lines = generate_gcode(decorated_mm, feed=feed,
                               field_w=field_w, field_h=field_h)
        try:
            save_gcode(fname, lines)
        except OSError as e:
            print(f"   Не удалось сохранить: {e}")
            continue

        # Печатаем статистику.
        segments = gcode_to_segments(lines)
        stats = segments_to_stats(segments)
        size = os.path.getsize(fname) / 1024
        print(f"\n   Готово: {fname}")
        print(f"   {len(lines)} строк, {size:.1f} КБ")
        print(f"   штрихов: {stats['draw_strokes']}, "
              f"переносов: {stats['travel_moves']}")


