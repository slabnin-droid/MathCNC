                ("cos()", lambda: self._insert("cos()", 4)),
                ("tan()", lambda: self._insert("tan()", 4)),
                ("t", lambda: self._insert("t")),
                ("√", lambda: self._insert("sqrt()", 5)),
                ("|x|", lambda: self._insert("abs()", 4)),
                ("a/b", lambda: self._insert("/")),
                ("x²", lambda: self._insert("**2")),
                ("xⁿ", lambda: self._insert("**()", 3)),
