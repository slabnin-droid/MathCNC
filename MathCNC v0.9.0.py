def glyph_strokes(ch, x, y, h):
    """
    Возвращает линии для одного символа в нужном месте и размере.

    Принимает:
        ch - символ (одна буква или цифра)
        x, y - левый-нижний угол квадрата, в который нужно вписать символ
        h - высота символа в миллиметрах

    Возвращает список линий в "настоящих" координатах на поле.
    Внутри шрифта координаты 0..1, здесь мы их растягиваем на размер h.
    """
    strokes = STROKE_FONT.get(ch, STROKE_FONT[' '])   # неизвестный символ = пробел
    w = h * 0.62                                      # пропорции буквы
    return [[(x + sx * w, y + sy * h) for sx, sy in st] for st in strokes]


def text_strokes(text, x, y, h):
    """
    Рисует целую строку текста и возвращает список линий.

    Каждый следующий символ сдвигается вправо на 0.72 от высоты —
    это расстояние между буквами.
    """
    out = []
    cx = x
    for ch in text:
        out.extend(glyph_strokes(ch, cx, y, h))
        cx += h * 0.72
    return out


def text_width(text, h):
    """
    Сколько миллиметров займёт строка при заданной высоте букв.

    Нужно, чтобы понять, влезет ли подпись в поле и как разместить её
    аккуратно возле графика.
    """
    return len(text) * h * 0.72



# МАРКЕРЫ (стрелки)
# ----------------------------------------------------------------------------
# Маленькая функция для стрелок на концах осей координат.

def marker_arrow(x, y, dx, dy, L=ARROW_LEN, angle_deg=ARROW_ANGLE_DEG):
    """
    Возвращает линии стрелки.

    x, y - точка, где кончик стрелки (вершина угла).
    dx, dy - направление оси (например, (1, 0) — вправо по оси X).
    L - длина "усиков" стрелки.
    angle_deg - угол между осью и усиком.
    """
    # Нормализуем направление: делаем вектор единичной длины.
    n = math.hypot(dx, dy) or 1.0
    dx, dy = dx / n, dy / n
    a = math.radians(angle_deg)
    ca, sa = math.cos(a), math.sin(a)

    # Два "усика" — под углом +angle и -angle к оси.
    sides = []
    for sign in (1, -1):
        rx = -dx * ca + dy * sa * sign
        ry = -dx * sa * sign - dy * ca
        sides.append((x + rx * L, y + ry * L))

    # Две короткие линии: от кончика к первому усику и ко второму.
    return [[(x, y), sides[0], (x, y), sides[1]]]


def marker_hole(x, y, radius_mm=1.2, segments=16):
    """
    Возвращает линии, из которых состоит "выколотая" точка —
    маленький пустой кружок вокруг координаты (x, y).

    Рисуется ломаной из segments коротких отрезков: так проще
    для станка (он и так умеет вести ломаную, а не дугу).

    radius_mm — радиус кружка в миллиметрах.
    Возвращает список линий — как и все остальные функции этого типа.
    """
    if radius_mm <= 0:
        return []
    pts = []
    for i in range(segments + 1):
        a = 2 * math.pi * i / segments
        pts.append((x + radius_mm * math.cos(a),
                    y + radius_mm * math.sin(a)))
    return [pts]



# ДЕЛЕНИЯ НА ОСЯХ И ЧИСЛА
# ----------------------------------------------------------------------------
# Чтобы оси были красивыми, шаг между делениями выбирается "круглым":
# 1, 2, 5, 10, 20, 50, 100 и т.д. А не что-то вроде 3.17 мм.


def nice_step(span, count_min):
    """
    Подбирает "красивый" шаг делений для промежутка длиной span.

    count_min — минимальное желаемое количество делений.
    Возвращает круглое число: 1, 2, 5, 10, 20 и т.д.
    """
    raw = span / max(count_min - 1, 1)
    if raw <= 0:
        return 1.0
    # Находим порядок числа (10, 100, 1000...).
    exp = math.floor(math.log10(raw))
    base = raw / (10 ** exp)       # число от 1 до 10
    # Округляем его до 1, 2, 5 или 10.
    if base < 1.5:
        nice = 1
    elif base < 3.5:
        nice = 2
    elif base < 7.5:
        nice = 5
    else:
        nice = 10
    return nice * (10 ** exp)


def nice_ticks(lo, hi, count_min=5):
    """
    Возвращает список "красивых" чисел-делений внутри [lo, hi].

    Пример: nice_ticks(-3, 7, 5) может вернуть [-2, 0, 2, 4, 6].
    """
    if hi <= lo:
        return [lo]
    step = nice_step(hi - lo, count_min)
    start = math.ceil(lo / step) * step   # первое деление >= lo
    ticks = []
    v = start
    while v <= hi + 1e-9:
        ticks.append(round(v, 10))
        v += step
    return ticks


def fmt_number(v):
    """
    Красиво печатает число для подписи на оси.

    Убирает лишние нули ("2.00" -> "2"), ставит запятую вместо точки
    ("3.5" -> "3,5"), для очень больших/маленьких чисел использует
    формат вида "1e6" или "1e-4".
    """
    if abs(v) < 1e-9:
        return "0"
    a = abs(v)
    if a >= 1e6 or a < 1e-3:
        # Для очень больших или очень маленьких — научный формат.
        s = f"{v:.1e}".replace("e+", "e")
        s = s.replace("e-0", "e-").replace("e+0", "e")
        return s.replace('.', ',')
    if abs(v - round(v)) < 1e-6:
        # Целое — печатаем без дробной части.
        return str(int(round(v)))
    # Иначе — до двух знаков, обрезаем нули справа, точку меняем на запятую.
    s = f"{v:.2f}".rstrip('0').rstrip('.')
    return s.replace('.', ',')


# ОСИ КООРДИНАТ
# ----------------------------------------------------------------------------
# Собираем всё, что нужно нарисовать помимо самого графика: линии осей,
# стрелки, деления, числа, буквы X/Y, отметку начала координат (0).


def build_axes(xmin, xmax, ymin, ymax, unit_mm, margin_mm):
    """
    Возвращает список линий, из которых состоят все оси.

    xmin..xmax, ymin..ymax — границы графика в "математических" единицах.
    unit_mm — сколько миллиметров в одном математическом шаге.
    margin_mm — на сколько миллиметров оси выходят за график.

    Задумка: оси идут по нулю, если ноль попадает в область графика
    (или с отступом, если нет). Всё остальное — деления, числа, буквы X/Y.
    """
    extra = []
    margin_math = margin_mm / unit_mm    # тот же отступ, но в математических единицах

    # Границы "чуть пошире" графика — на этот отступ.
    data_x_lo = xmin - margin_math
    data_x_hi = xmax + margin_math
    data_y_lo = ymin - margin_math
    data_y_hi = ymax + margin_math

    # Попадает ли ноль в наш график по каждой оси?
    has_origin_x = data_x_lo <= 0 <= data_x_hi
    has_origin_y = data_y_lo <= 0 <= data_y_hi

    # --- где рисовать вертикальную ось Y (по горизонтали) ---
    if has_origin_x:
        x_lo_math = data_x_lo
        x_hi_math = data_x_hi
        axis_y_x_mm = 0.0                     # ось Y проходит через x=0
    else:
        x_lo_math = data_x_lo
        x_hi_math = data_x_hi
        # Если ноль не попал — ось Y прижимается к ближайшему краю.
        if 0 < data_x_lo:
            axis_y_x_mm = data_x_lo * unit_mm
        else:
            axis_y_x_mm = data_x_hi * unit_mm

    # --- где рисовать горизонтальную ось X (по вертикали) ---
    if has_origin_y:
        y_lo_math = data_y_lo
        y_hi_math = data_y_hi
        axis_x_y_mm = 0.0                     # ось X проходит через y=0
    else:
        y_lo_math = data_y_lo
        y_hi_math = data_y_hi
        if 0 < data_y_lo:
            axis_x_y_mm = data_y_lo * unit_mm
        else:
            axis_x_y_mm = data_y_hi * unit_mm

    # Переводим границы в миллиметры.
    x_lo = x_lo_math * unit_mm
    x_hi = x_hi_math * unit_mm
    y_lo = y_lo_math * unit_mm
    y_hi = y_hi_math * unit_mm

    #   Ось X: горизонтальная линия + стрелка + буква "X" 
    extra.append([(x_lo, axis_x_y_mm), (x_hi, axis_x_y_mm)])
    extra.extend(marker_arrow(x_hi, axis_x_y_mm, 1.0, 0.0))
    extra.extend(text_strokes("X", x_hi + 1.0,
                             axis_x_y_mm - LABEL_H / 2, LABEL_H))

    # Если ноль по Y не попал в график, подпишем, где именно проходит ось.
    if not has_origin_y:
        lbl = f"y = {fmt_number(axis_x_y_mm / unit_mm)}"
        extra.extend(text_strokes(lbl, x_lo + 1.0,
                                 axis_x_y_mm + TICK_LEN / 2 + 0.5,
                                 TICK_LABEL_H * 0.8))

    #   Ось Y: вертикальная линия + стрелка + буква "Y" 
    extra.append([(axis_y_x_mm, y_lo), (axis_y_x_mm, y_hi)])
    extra.extend(marker_arrow(axis_y_x_mm, y_hi, 0.0, 1.0))
    extra.extend(text_strokes("Y", axis_y_x_mm + 1.0,
                             y_hi + 1.0, LABEL_H))

    if not has_origin_x:
        lbl = f"x = {fmt_number(axis_y_x_mm / unit_mm)}"
        extra.extend(text_strokes(lbl,
                                 axis_y_x_mm + TICK_LEN / 2 + 0.5,
                                 y_lo + 1.0, TICK_LABEL_H * 0.8))

    #      Деления по оси X с числами 
    x_ticks = nice_ticks(x_lo_math, x_hi_math, TICK_COUNT_MIN)
    for v in x_ticks:
        if has_origin_x and abs(v) < 1e-9:
            continue   # не рисуем деление в самом нуле - там пересечение осей
        vm = v * unit_mm
        # Сам штрих — короткая вертикальная чёрточка поперёк оси.
        extra.append([(vm, axis_x_y_mm - TICK_LEN / 2),
                      (vm, axis_x_y_mm + TICK_LEN / 2)])
        # Число под/над штрихом.
        lbl = fmt_number(v)
        tx = vm - text_width(lbl, TICK_LABEL_H) / 2
        if has_origin_y:
            ty = axis_x_y_mm - TICK_LEN / 2 - TICK_LABEL_H - 0.4
        else:
            ty = axis_x_y_mm + TICK_LEN / 2 + 0.4
        extra.extend(text_strokes(lbl, tx, ty, TICK_LABEL_H))

    # ----- Деления по оси Y с числами -----
    y_ticks = nice_ticks(y_lo_math, y_hi_math, TICK_COUNT_MIN)
    for v in y_ticks:
        if has_origin_y and abs(v) < 1e-9:
            continue
        vm = v * unit_mm
        extra.append([(axis_y_x_mm - TICK_LEN / 2, vm),
                      (axis_y_x_mm + TICK_LEN / 2, vm)])
        lbl = fmt_number(v)
        if has_origin_x:
            tx = axis_y_x_mm - TICK_LEN / 2 - text_width(lbl, TICK_LABEL_H) - 0.4
        else:
            tx = axis_y_x_mm + TICK_LEN / 2 + 0.4
        ty = vm - TICK_LABEL_H / 2
        extra.extend(text_strokes(lbl, tx, ty, TICK_LABEL_H))

    # ----- Отметка единичного отрезка (число "1") -----
    # Если в графике есть 1 на оси, но её нет среди обычных делений,
    # добавляем специальную отметку — чтобы было видно масштаб.
    if (has_origin_x and unit_mm >= 1.5
            and x_lo_math <= 1.0 <= x_hi_math
            and not any(abs(v - 1.0) < 1e-6 for v in x_ticks)):
        vm = 1.0 * unit_mm
        extra.append([(vm, axis_x_y_mm - TICK_LEN * 0.8),
                      (vm, axis_x_y_mm + TICK_LEN * 0.8)])
        tx = vm - text_width("1", TICK_LABEL_H) / 2
        ty = axis_x_y_mm - TICK_LEN * 0.8 - TICK_LABEL_H - 0.4
        extra.extend(text_strokes("1", tx, ty, TICK_LABEL_H))

    if (has_origin_y and unit_mm >= 1.5
            and y_lo_math <= 1.0 <= y_hi_math
            and not any(abs(v - 1.0) < 1e-6 for v in y_ticks)):
        vm = 1.0 * unit_mm
        extra.append([(axis_y_x_mm - TICK_LEN * 0.8, vm),
                      (axis_y_x_mm + TICK_LEN * 0.8, vm)])
        tx = axis_y_x_mm - TICK_LEN * 0.8 - text_width("1", TICK_LABEL_H) - 0.4
        ty = vm - TICK_LABEL_H / 2
        extra.extend(text_strokes("1", tx, ty, TICK_LABEL_H))

    #       Буква "O" (начало координат) 
    # Рисуем её чуть левее и ниже точки (0, 0), чтобы не наложить на оси.
    if has_origin_x and has_origin_y:
        h = TICK_LABEL_H * 0.85
        ox = -text_width("O", h) - 0.5
        oy = -h - 0.5
        extra.extend(text_strokes("O", ox, oy, h))

    return extra



# ПОДПИСИ ФОРМУЛ
# ----------------------------------------------------------------------------
# Здесь мы формируем красивый текст вида "y = 2x² + 3" из коэффициентов.
# Это то, что станок потом напишет рядом с графиком.


def join_terms(terms):
    """
    Склеивает список слагаемых через " + " или " - ".

    Пример: ["2x", "-3"] -> "2x - 3", ["2x", "3"] -> "2x + 3".
    Пустой список -> "0".
    """
    if not terms:
        return "0"
    out = terms[0]
    for t in terms[1:]:
        # Если слагаемое начинается с минуса — слитно " - ", иначе " + ".
        out += (" - " + t[1:]) if t.startswith('-') else (" + " + t)
    return out


def format_power(coeff, var, degree):
    """
    Форматирует одно слагаемое с переменной в степени.

    Пример: format_power(2, "x", 2) -> "2x²".
    Коэффициент 1 опускаем ("x²", а не "1x²"), -1 даёт "-x²".
    """
    if abs(coeff) < 1e-12:
        return ""    # коэффициент ноль — слагаемого нет
    v = var + ("²" if degree == 2 else "³" if degree == 3 else "")
    if abs(coeff - 1) < 1e-12:
        return v
    if abs(coeff + 1) < 1e-12:
        return "-" + v
    return fmt_number(coeff) + v


def label_linear(k, b, var="x"):
    """Подпись для прямой: "y = kx + b" (с учётом частных случаев)."""
    terms = [t for t in (format_power(k, var, 1),
                         fmt_number(b) if abs(b) > 1e-12 else "") if t]
    return f"y = {join_terms(terms)}"


def label_quadratic(a, b, c, var="x"):
    """Подпись для параболы: "y = ax² + bx + c"."""
    terms = [t for t in (format_power(a, var, 2),
                         format_power(b, var, 1),
                         fmt_number(c) if abs(c) > 1e-12 else "") if t]
    return f"y = {join_terms(terms)}"


def label_cubic(a, b, c, d, var="x"):
    """Подпись для кубической кривой: "y = ax³ + bx² + cx + d"."""
    terms = [t for t in (format_power(a, var, 3),
                         format_power(b, var, 2),
                         format_power(c, var, 1),
                         fmt_number(d) if abs(d) > 1e-12 else "") if t]
    return f"y = {join_terms(terms)}"


def label_hyperbola(k, var="x"):
    """Подпись для гиперболы: "y = k/x", частные случаи "1/x" и "-1/x"."""
    if abs(k) < 1e-12:
        return "y = 0"
    if abs(k - 1) < 1e-12:
        return f"y = 1/{var}"
    if abs(k + 1) < 1e-12:
        return f"y = -1/{var}"
    return f"y = {fmt_number(k)}/{var}"


def label_sqrt(a, var="x"):
    """Подпись для корня: "y = √x" или "y = a√x"."""
    if abs(a) < 1e-12:
        return "y = 0"
    if abs(a - 1) < 1e-12:
        return f"y = √{var}"
    if abs(a + 1) < 1e-12:
        return f"y = -√{var}"
    return f"y = {fmt_number(a)}√{var}"


def label_trig(name, A, omega, phi, var="x"):
    """
    Подпись для синуса/косинуса/тангенса: "y = A·sin(ωx + φ)".

    Все части аккуратно форматируются: коэффициент 1 не показываем,
    ω=1 даёт просто "x", φ без знака не выводим.
    """
    if abs(A) < 1e-12:
        return "y = 0"
    a_str = "" if abs(A - 1) < 1e-12 else "-" if abs(A + 1) < 1e-12 else fmt_number(A)
    arg_terms = []
    if abs(omega) > 1e-12:
        if abs(omega - 1) < 1e-12:
            arg_terms.append(var)
        elif abs(omega + 1) < 1e-12:
            arg_terms.append("-" + var)
        else:
            arg_terms.append(fmt_number(omega) + var)
    if abs(phi) > 1e-12:
        arg_terms.append(fmt_number(phi))
    arg = join_terms(arg_terms) if arg_terms else "0"
    return f"y = {a_str}{name}({arg})"


def label_abs(a, b, var="x"):
    """Подпись для модуля: "y = a|x| + b"."""
    terms = []
    if abs(a) > 1e-12:
        if abs(a - 1) < 1e-12:
            terms.append(f"|{var}|")
        elif abs(a + 1) < 1e-12:
            terms.append(f"-|{var}|")
        else:
            terms.append(f"{fmt_number(a)}|{var}|")
    if abs(b) > 1e-12:
        terms.append(fmt_number(b))
    return f"y = {join_terms(terms) if terms else '0'}"


def pretty_formula(expr):
    """
    Приводит текст формулы к красивому виду для подписи.

    Пример: "2*t**2 + 3*t" -> "2t² + 3t".
    """
    s = expr.strip()
    s = s.replace("**", "^").replace("^2", "²").replace("^3", "³")
    # Убираем "*" перед буквой или скобкой: "2*t" -> "2t", "3*(t+1)" -> "3(t+1)".
    s = re.sub(r'\*(?=[a-zA-Z(])', '', s)
    # Убираем "1" перед буквой: "1t" -> "t".
    s = re.sub(r'(?<![\d.])1(?=[a-zA-Z(])', '', s)
    # "-1t" -> "-t".
    s = re.sub(r'-1(?=[a-zA-Z(])', '-', s)
    # Красиво ставим пробелы вокруг действий.
    s = re.sub(r'\s*\+\s*', ' + ', s)
    s = re.sub(r'\s*-\s*', ' - ', s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def custom_label(x_expr, y_expr):
    """Подпись для параметрической кривой: "x = ..., y = ..."."""
    return f"x = {pretty_formula(x_expr)}, y = {pretty_formula(y_expr)}"



# РАЗМЕЩЕНИЕ ПОДПИСИ
# ----------------------------------------------------------------------------
# Подпись "y = 2x + 1" нужно поставить рядом с графиком так, чтобы она
# не налезала на сам график и на оси. Пробуем четыре позиции (вокруг
# графика) и выбираем ту, где меньше всего "перекрытия".


def rects_intersect(a, b, eps=1e-6):
    """
    Проверяет, пересекаются ли два прямоугольника.

    Прямоугольник — это кортеж (x1, y1, x2, y2), где (x1, y1) —
    левый-нижний угол, (x2, y2) — правый-верхний.
    """
    return not (a[2] + eps < b[0] or b[2] + eps < a[0]
                or a[3] + eps < b[1] or b[3] + eps < a[1])


def rect_area(r):
    """Площадь прямоугольника."""
    return max(0.0, r[2] - r[0]) * max(0.0, r[3] - r[1])


def inter_area(a, b):
    """
    Площадь пересечения двух прямоугольников (0, если не пересекаются).
    """
    return rect_area((max(a[0], b[0]), max(a[1], b[1]),
                      min(a[2], b[2]), min(a[3], b[3])))


def build_curve_label(unit_mm, label_text, xmin, xmax, ymin, ymax):
    """
    Размещает подпись функции около графика и возвращает линии для неё.

    Пробуем четыре места: справа-сверху, слева-сверху, справа-снизу,
    слева-снизу от графика. Каждое проверяем на "налезание" на сам график
    и на оси. Выбираем то, где перекрытие минимально (в идеале — ноль).
    """
    if not label_text:
        return []
    h = CRV_LABEL_H
    w = text_width(label_text, h)
    pad, off = 1.0, CRV_LABEL_OFFSET

    # Границы графика в миллиметрах.
    fx0, fx1 = xmin * unit_mm, xmax * unit_mm
    fy0, fy1 = ymin * unit_mm, ymax * unit_mm

    # Четыре возможных прямоугольника для подписи.
    candidates = [
        (fx1 + off, fy1 + pad, fx1 + off + w, fy1 + pad + h),           # справа сверху
        (fx0 - off - w, fy1 + pad, fx0 - off, fy1 + pad + h),           # слева сверху
        (fx1 + off, fy0 - pad - h, fx1 + off + w, fy0 - pad),           # справа снизу
        (fx0 - off - w, fy0 - pad - h, fx0 - off, fy0 - pad),           # слева снизу
    ]

    # Прямоугольник самого графика и узкие "полоски" осей (если они есть).
    figure_rect = (fx0, fy0, fx1, fy1)
    x_axis_rect = (fx0 - off, -0.3, fx1 + off, 0.3) if ymin <= 0 <= ymax else None
    y_axis_rect = (-0.3, fy0 - off, 0.3, fy1 + off) if xmin <= 0 <= xmax else None

    best, best_overlap = None, None
    for rect in candidates:
        strokes = text_strokes(label_text, rect[0], rect[1], h)
        overlap = 0.0
        if rects_intersect(rect, figure_rect):
            overlap += inter_area(rect, figure_rect)
        if x_axis_rect and rects_intersect(rect, x_axis_rect):
            overlap += inter_area(rect, x_axis_rect)
        if y_axis_rect and rects_intersect(rect, y_axis_rect):
            overlap += inter_area(rect, y_axis_rect)
        # Если этот вариант лучше (меньше перекрытие) — запоминаем.
        if best_overlap is None or overlap < best_overlap:
            best_overlap, best = overlap, strokes
            if overlap == 0:
                break   # идеально — можно дальше не искать
    return best or []


# АВТОМАСШТАБ
# ----------------------------------------------------------------------------
# Когда пользователь нажимает "Авто", нужно подобрать такой "единичный
# отрезок" (unit_mm), чтобы график с осями и подписью красиво влез
# в рабочее поле. Здесь мы это и вычисляем.


def fit_unit_to_field(w_math, h_math, field_w, field_h,
                      max_unit=MAX_UNIT, label_text=""):
    """
    Подбирает единичный отрезок так, чтобы всё влезло в поле.

    Идея: берём максимально возможный unit и постепенно уменьшаем,
    пока "габариты с запасом" не поместятся в поле.
    Метод "проб и ошибок" — за 30 итераций обычно сходится.

    Возвращает подобранный unit_mm.
    """
    # Ширина и высота графика в математических единицах (минимум 1e-6).
    w_eff = max(w_math, 1e-6)
    h_eff = max(h_math, 1e-6)

    # Сколько места займёт подпись (если она есть).
    label_w = text_width(label_text, CRV_LABEL_H) + CRV_LABEL_OFFSET \
        if label_text else 0.0
    label_h = CRV_LABEL_H if label_text else 0.0

    # Начинаем с максимального размера и уменьшаем.
    unit = max_unit
    for _ in range(30):
        w_mm, h_mm = w_eff * unit, h_eff * unit
        # Отступ вокруг осей — та же логика, что и при реальной сборке.
        overhang = (_compute_auto_margin(w_mm, h_mm)
                    + TICK_LABEL_H + LABEL_H)
        total_w = w_mm + label_w + 2 * overhang + 2 * FIELD_MARGIN
        total_h = h_mm + label_h + 2 * overhang + 2 * FIELD_MARGIN
        # Всё влезает — возвращаем текущий unit.
        if total_w <= field_w and total_h <= field_h:
            return unit
        # Не влезает — уменьшаем пропорционально тому, насколько не влезает.
        scale = min(field_w / total_w, field_h / total_h) * 0.98
        unit *= scale
        if unit < 0.01:      # совсем крошечный — дальше нет смысла
            return unit
    return unit



# СБОРКА ЧЕРТЕЖА
# ----------------------------------------------------------------------------
# Здесь всё соединяется: график + оси + подпись, повернуть/сдвинуть так,
# чтобы красиво легло на рабочее поле.

def _snap_left(align, ax_min, ax_max, field_w):
    """
    Считает, на сколько миллиметров надо сдвинуть по горизонтали,
    чтобы рисунок встал слева/по центру/справа.
    """
    if align == "left":
        target = FIELD_MARGIN
        # Прижимаем к сетке, чтобы цифры были "круглыми".
        target = math.ceil(target / GRID_STEP_MM) * GRID_STEP_MM
        return target - ax_min
    if align == "right":
        target = field_w - FIELD_MARGIN
        target = math.floor(target / GRID_STEP_MM) * GRID_STEP_MM
        return target - ax_max
    # По центру: сдвигаем так, чтобы центр рисунка совпал с центром поля.
    return field_w / 2 - (ax_min + ax_max) / 2


def _snap_bottom(align, ay_min, ay_max, field_h):
    """
    То же самое, но по вертикали: снизу / по центру / сверху.
    """
    if align == "bottom":
        target = FIELD_MARGIN
        target = math.ceil(target / GRID_STEP_MM) * GRID_STEP_MM
        return target - ay_min
    if align == "top":
        target = field_h - FIELD_MARGIN
        target = math.floor(target / GRID_STEP_MM) * GRID_STEP_MM
        return target - ay_max
    return field_h / 2 - (ay_min + ay_max) / 2


def _compute_auto_margin(w_mm, h_mm):
    """
    Считает, насколько оси должны выступать за график (в мм).

    Обычно это 10% от размера графика, но не меньше 8 мм.
    Отдельно обрабатываем "плоские" графики (например, y = 5 — просто
    горизонтальная линия): иначе отступ раздувается и линия тонет
    в пустом поле.
    """
    margin = max(AXES_MIN_MARGIN,
                 AXES_MARGIN_RATIO * max(w_mm, h_mm, 1.0))
    # Плоский по высоте график — ограничиваем отступ 15% от ширины.
    if h_mm < 1e-6:
        margin = max(AXES_MIN_MARGIN,
                     min(margin, 0.15 * max(w_mm, 1.0)))
    # Плоский по ширине — то же самое, но наоборот.
    if w_mm < 1e-6:
        margin = max(AXES_MIN_MARGIN,
                     min(margin, 0.15 * max(h_mm, 1.0)))
    return margin


def _build_drawing_inner(curves_math, unit_mm, draw_axes, curve_label_text,
                         offset_x_mm, offset_y_mm, align_x, align_y,
                         field_w, field_h):
    """
    Внутренняя сборка чертежа (без цикла подгонки масштаба).

    Берёт кривые, добавляет оси и подпись, сдвигает всё в нужное место
    поля. Возвращает (список готовых линий, информация о размещении).
    """
    curves = normalize_curves(curves_math)
    check_curves(curves)

    # --- НОВОЕ: ищем выколотые точки ---
    hole_strokes_mm = []
    hole_info = getattr(_build_drawing_inner, "_last_holes", None)
    if hole_info:
        for hx, hy in hole_info:
            hole_strokes_mm.extend(
                marker_hole(hx * unit_mm, hy * unit_mm))
    # ------------------------------------

    # Находим границы графика.
    all_pts = [p for c in curves for p in c]
    xmin = min(p[0] for p in all_pts)
    xmax = max(p[0] for p in all_pts)
    ymin = min(p[1] for p in all_pts)
    ymax = max(p[1] for p in all_pts)

    # Переводим точки графика из "математики" в миллиметры.
    curves_mm = [[(x * unit_mm, y * unit_mm) for x, y in c] for c in curves]

    # Размер графика в миллиметрах и отступ для осей.
    w_mm = (xmax - xmin) * unit_mm
    h_mm = (ymax - ymin) * unit_mm
    auto_margin = _compute_auto_margin(w_mm, h_mm)

    # Собираем линии осей и подписи.
    axes_strokes = []
    if draw_axes:
        axes_strokes = build_axes(xmin, xmax, ymin, ymax,
                                  unit_mm, auto_margin)

    label_strokes = []
    if curve_label_text:
        label_strokes = build_curve_label(unit_mm, curve_label_text,
                                          xmin, xmax, ymin, ymax)

    # Общий габарит: оси + график + подпись. Используется для выравнивания.
    align_group = axes_strokes + curves_mm + label_strokes + hole_strokes_mm
    ax_all = [x for c in align_group for x, _ in c]
    ay_all = [y for c in align_group for _, y in c]
    ax_min, ax_max = min(ax_all), max(ax_all)
    ay_min, ay_max = min(ay_all), max(ay_all)

    used_w = ax_max - ax_min
    used_h = ay_max - ay_min

    # Считаем сдвиг под выбранное выравнивание.
    ox = _snap_left(align_x, ax_min, ax_max, field_w) + offset_x_mm
    oy = _snap_bottom(align_y, ay_min, ay_max, field_h) + offset_y_mm

    # Если после сдвига что-то вылезло за поле — центрируем принудительно.
    fits_x = (ax_min + ox >= -0.01 and ax_max + ox <= field_w + 0.01)
    fits_y = (ay_min + oy >= -0.01 and ay_max + oy <= field_h + 0.01)
    if not (fits_x and fits_y):
        ox = field_w / 2 - (ax_min + ax_max) / 2 + offset_x_mm
        oy = field_h / 2 - (ay_min + ay_max) / 2 + offset_y_mm

    # Подпись сдвигаем вслед за всем остальным.
    if label_strokes:
        label_strokes = [[(x + ox, y + oy) for x, y in c]
                         for c in label_strokes]
        # Если подпись всё же вылезает за край — подтягиваем её внутрь поля.
        lx_all = [x for c in label_strokes for x, _ in c]
        ly_all = [y for c in label_strokes for _, y in c]
        lx_min, lx_max = min(lx_all), max(lx_all)
        ly_min, ly_max = min(ly_all), max(ly_all)
        dx = dy = 0.0
        if lx_min < 0:
            dx = -lx_min
        elif lx_max > field_w:
            dx = field_w - lx_max
        if ly_min < 0:
            dy = -ly_min
        elif ly_max > field_h:
            dy = field_h - ly_max
        if dx or dy:
            label_strokes = [[(x + dx, y + dy) for x, y in c]
                             for c in label_strokes]

    # --- Собираем итоговый список линий ---
    # Порядок важен: сначала оси, потом график (чтобы каретка шла
    # сначала по чистому листу с осями, а уже потом рисовала кривую).
    decorated = axes_strokes + list(curves_mm)
    decorated_mm = [[(x + ox, y + oy) for x, y in c] for c in decorated]

    # --- НОВОЕ: сдвигаем кружки туда же, куда сдвинули всё остальное ---
    if hole_strokes_mm:
        decorated_mm.extend(
            [[(x + ox, y + oy) for x, y in c] for c in hole_strokes_mm])
    # ---------------------------------------------------------------

    decorated_mm.extend(label_strokes)

    # Финальная проверка "влезло ли всё".
    fits = (ax_min + ox >= -0.01 and ax_max + ox <= field_w + 0.01
            and ay_min + oy >= -0.01 and ay_max + oy <= field_h + 0.01)

    info = {
        "bbox_math": (xmin, xmax, ymin, ymax),
        "offset_mm": (ox, oy),
        "unit_mm": unit_mm,
        "fits": fits,
        "used_w": used_w,
        "used_h": used_h,
    }
    return decorated_mm, info


def build_drawing(curves_math, unit_mm, draw_axes, curve_label_text,
                  offset_x_mm=0.0, offset_y_mm=0.0,
                  align_x="left", align_y="bottom",
                  field_w=FIELD_W_DEFAULT, field_h=FIELD_H_DEFAULT):
    """
    Полная сборка чертежа: с автоматической подгонкой масштаба.

    Если с заданным unit_mm всё не влезает в поле — несколько раз
    уменьшаем unit и пробуем снова. Максимум 12 попыток, обычно хватает
    одной-двух.

    Возвращает (список линий, информация о размещении).
    """
    if unit_mm <= 0:
        unit_mm = 1.0

    # Первая попытка с тем, что попросили.
    result = _build_drawing_inner(
        curves_math, unit_mm, draw_axes, curve_label_text,
        offset_x_mm, offset_y_mm, align_x, align_y,
        field_w, field_h)

    for _ in range(12):
        _, info = result
        w_used = info["used_w"]
        h_used = info["used_h"]
        if w_used <= 0 or h_used <= 0:
            return result

        # Всё уже влезает — отдаём результат как есть.
        if w_used <= field_w and h_used <= field_h:
            return result

        # Не влезает — уменьшаем масштаб и пробуем снова.
        scale = min(field_w / w_used, field_h / h_used) * 0.98
        if scale >= 0.999:
            return result
        unit_mm *= scale
        if unit_mm < 0.001:      # совсем крошечный — дальше некуда
            return result
        result = _build_drawing_inner(
            curves_math, unit_mm, draw_axes, curve_label_text,
            offset_x_mm, offset_y_mm, align_x, align_y,
            field_w, field_h)

    return result



# G-КОД
# ----------------------------------------------------------------------------
# Превращаем линии чертежа в команды для станка.
# Каждая линия превращается в: подъехать → опустить ручку → провести → поднять.

# Первые строки любой программы - стандартный "заголовок".
GCODE_HEADER = [
    "(Math.CNC.0.9.0)",   
    "M3",                         # включение охлаждения
    "G21",                        # работать в миллиметрах
    "G90",                        # абсолютные координаты (от нуля станка)
    "G10 L20 P1 X0 Y0",           # считать текущее положение нулём координат
]


def chain_strokes(strokes, threshold=CHAIN_THRESHOLD):
    """
    Склеивает близкие штрихи в один, чтобы станок меньше поднимал ручку.

    Если конец одного штриха ближе к началу следующего, чем на threshold
    миллиметров, мы их объединяем. Это экономит время и уменьшает
    количество "переездов".
    """
    if not strokes:
        return []
    result = []
    for s in strokes:
        if not s:
            continue
        if not result:
            result.append(list(s))
            continue
        lx, ly = result[-1][-1]     # последняя точка предыдущего штриха
        fx, fy = s[0]                # первая точка текущего
        if math.hypot(fx - lx, fy - ly) <= threshold:
            # Близко — приклеиваем к предыдущему.
            result[-1].extend(s)
        else:
            # Далеко — начинаем новый штрих.
            result.append(list(s))
    return result


def _liang_barsky(p0, p1, xmin, xmax, ymin, ymax):
    """
    Обрезает отрезок прямоугольником [xmin..xmax, ymin..ymax].

    Метод простой: идём по отрезку от начала к концу и смотрим, в какой
    момент он входит в прямоугольник и в какой выходит. Если совсем не
    заходит — возвращаем пустой список.

    Возвращает список из одной пары (начало, конец) — то есть либо
    весь отрезок, либо его часть, либо ничего.
    """
    x0, y0 = p0
    x1, y1 = p1
    dx = x1 - x0
    dy = y1 - y0
    t0, t1 = 0.0, 1.0

    # Проверяем по каждой стороне прямоугольника.
    for p, q in ((-dx, x0 - xmin), (dx, xmax - x0),
                 (-dy, y0 - ymin), (dy, ymax - y0)):
        if abs(p) < 1e-12:
            # Отрезок параллелен этой стороне. Если снаружи - отбрасываем.
            if q < -1e-12:
                return []
            continue
        r = q / p
        if p < 0:
            if r > t1:
                return []
            if r > t0:
                t0 = r
        else:
            if r < t0:
                return []
            if r < t1:
                t1 = r

    if t0 >= t1 - 1e-12:
        return []
    return [((x0 + t0 * dx, y0 + t0 * dy),
             (x0 + t1 * dx, y0 + t1 * dy))]


def clip_stroke_to_field(stroke, fw, fh):
    """
    Обрезает весь штрих по прямоугольнику [0..fw, 0..fh].

    Штрих — это ломаная (много точек). Если часть вылезает за поле,
    отрезаем её. Внутри собираем куски, которые целиком в поле.
    Возвращает список кусков-ломаных.
    """
    pieces = []
    current = None
    for i in range(len(stroke) - 1):
        a, b = stroke[i], stroke[i + 1]
        clipped = _liang_barsky(a, b, 0, fw, 0, fh)
        for pa, pb in clipped:
            if current is None:
                current = [pa, pb]
            elif (abs(current[-1][0] - pa[0]) < 1e-6
                  and abs(current[-1][1] - pa[1]) < 1e-6):
                # Куски стыкуются - продолжаем ту же ломаную.
                current.append(pb)
            else:
                # Разрыв - начинаем новый кусок.
                if len(current) >= 2:
                    pieces.append(current)
                current = [pa, pb]
    if current and len(current) >= 2:
        pieces.append(current)
    return pieces


def generate_gcode(decorated_mm, feed=FEED_DEFAULT,
                   decimals=DECIMALS_DEFAULT,
                   chain_threshold=CHAIN_THRESHOLD,
                   field_w=FIELD_W_DEFAULT, field_h=FIELD_H_DEFAULT):
    """
    Превращает список линий в строки G-кода.

    Для каждой линии:
      1. Поднять ручку.
      2. Переехать в начало линии.
      3. Опустить ручку.
      4. Провести по всем точкам линии.
      5. Поднять ручку.
    Всё, что вылезает за рабочее поле, обрезается.

    Возвращает список строк G-кода.
    """
    lines = list(GCODE_HEADER)
    lines.append(f"G0 Z{Z_UP:.{decimals}f}")     # поднимаем ручку в начале

    # Склеиваем близкие штрихи (если разрешено).
    strokes = chain_strokes(decorated_mm, chain_threshold) \
        if chain_threshold > 0 else decorated_mm

    for c in strokes:
        if len(c) < 2:
            continue
        # Обрезаем по полю.
        pieces = clip_stroke_to_field(c, field_w, field_h)
        for piece in pieces:
            if len(piece) < 2:
                continue
            x0, y0 = piece[0]
            # 1. Подъехать в начало.
            lines.append(f"G0 X{x0:.{decimals}f} Y{y0:.{decimals}f}")
            # 2. Опустить ручку.
            lines.append(f"G1 Z{Z_DOWN:.{decimals}f} F{Z_FEED}")
            # 3. Провести по точкам линии.
            for x, y in piece[1:]:
                lines.append(
                    f"G1 X{x:.{decimals}f} Y{y:.{decimals}f} F{feed}")
            # 4. Поднять ручку.
            lines.append(f"G0 Z{Z_UP:.{decimals}f}")
    lines.append("M2")           # конец программы
    return lines


def save_gcode(path, lines):
    """
    Записывает G-код в файл.

    Используем ASCII (так требует большинство станков) и Unix-переводы
    строк (LF), чтобы файл читался одинаково везде.
    """
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")



# СИМУЛЯЦИЯ G-КОДА
# ----------------------------------------------------------------------------
# Чтобы показать анимацию, нужно "поиграть" G-код как станок:
# прочитать строки, понять, где ручка пишет, где просто едет.


def gcode_to_segments(gcode_lines, z_threshold=1.5, split_len=1.0):
    """
    Разбирает G-код на маленькие отрезки для анимации.

    Каждый отрезок — кортеж:
        (тип, точка_начала, точка_конца, номер_строки_в_файле)
    тип = "draw" если ручка была опущена, иначе "travel".

    Длинные отрезки делятся на части длиной ~split_len, чтобы анимация
    шла плавно и подсвечивалась нужная строка G-кода.
    """
    segments = []
    cur = (0.0, 0.0)      # текущая позиция станка
    pen_down = False      # опущена ли ручка

    for line_idx, raw in enumerate(gcode_lines):
        s = raw.strip()
        # Пропускаем пустые строки, комментарии и конец программы.
        if not s or s.startswith("(") or s.startswith("M2"):
            continue
        if s.startswith(("G21", "G90", "G10")):
            continue

        m = re.match(r'G(\d+)', s)
        if not m:
            continue
        gnum = int(m.group(1))

        # Достаём координаты из строки.
        xm = re.search(r'X(-?\d+\.?\d*)', s)
        ym = re.search(r'Y(-?\d+\.?\d*)', s)
        zm = re.search(r'Z(-?\d+\.?\d*)', s)
        nx = float(xm.group(1)) if xm else cur[0]
        ny = float(ym.group(1)) if ym else cur[1]

        if zm:
            # Команда только с Z - меняется состояние ручки.
            pen_down = float(zm.group(1)) < z_threshold
            cur = (nx, ny)
            continue

        if gnum in (0, 1):
            # Движение по X/Y. Тип зависит от того, опущена ли ручка.
            kind = "draw" if pen_down else "travel"
            dx, dy = nx - cur[0], ny - cur[1]
            L = math.hypot(dx, dy)
            parts = max(1, int(math.ceil(L / split_len)))
            # Режем длинный отрезок на куски.
            for i in range(parts):
                t0 = i / parts
                t1 = (i + 1) / parts
                p0 = (cur[0] + dx * t0, cur[1] + dy * t0)
                p1 = (cur[0] + dx * t1, cur[1] + dy * t1)
                segments.append((kind, p0, p1, line_idx))
            cur = (nx, ny)
    return segments


def segments_to_stats(segments):
    """
    Считает статистику по отрезкам: количество штрихов, переездов, длину.
    Показывается в интерфейсе.
    """
    draw_strokes = 0        # сколько раз ручка опускалась
    travel_moves = 0        # сколько было переездов без рисования
    total_draw_mm = 0.0     # суммарная длина всех линий
    max_travel_mm = 0.0     # самый длинный одиночный переезд
    prev_kind = None
    draw_points = 0         # количество точек, где рисовали

    for seg in segments:
        kind, a, b = seg[0], seg[1], seg[2]
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        if kind == "draw":
            total_draw_mm += L
            draw_points += 1
            if prev_kind != "draw":
                # Первый "рисующий" отрезок подряд = новый штрих.
                draw_strokes += 1
        else:
            max_travel_mm = max(max_travel_mm, L)
            if prev_kind == "draw":
                # После рисования пошёл переезд - считаем.
                travel_moves += 1
        prev_kind = kind

    return {
        "draw_strokes": draw_strokes,
        "travel_moves": travel_moves,
        "draw_points": draw_points,
        "total_draw_mm": total_draw_mm,
        "max_travel_mm": max_travel_mm,
    }



